ARABIC_DIACRITICS_RE = re.compile(r"[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]")


def norm_ar(text: str) -> str:
    s = ARABIC_DIACRITICS_RE.sub("", text)
    s = re.sub(r"[أإآٱ]", "ا", s)
    s = s.replace("ى", "ي").replace("ة", "ه").replace("ؤ", "و").replace("ئ", "ي")
    s = re.sub(r"[^\u0621-\u063A\u0641-\u064A0-9\s]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def load_surah_names() -> dict[int, str]:
    raw = QURAN_META_PATH.read_text(encoding="utf-8")
    names: dict[int, str] = {}
    for m in re.finditer(r"number:\s*(\d+)\s*,\s*name:\s*['\"]([^'\"]+)['\"]", raw):
        names[int(m.group(1))] = m.group(2)
    return names


