    all_events = []
    for v in (1, 2, 3, 4):
        vol_events = []
        v_secs = [s for s in toc_sections if s["volume"] == v]
        for sec in v_secs:
            # Find characters & classical sources cited inside this section's pages
            sec_text_parts = [
                matn_pages_by_vol[v][p]["fullText"]
                for p in sorted(matn_pages_by_vol[v])
                if sec["startPage"] <= p <= sec["endPage"]
            ]
            joined_sec = "\n".join(sec_text_parts)
            sec_chars = [
                cid
                for cid, _, _, _, _, aliases in CHARACTERS_SPEC
                if any(a in joined_sec for a in aliases)
            ]
            sec_sources = [
                sid
                for sid, _, _, _, pats in CLASSICAL_SOURCES_SPEC
                if any(re.search(p, joined_sec) for p in pats)
            ]
            sub_events = []
            for p in sorted(matn_pages_by_vol[v]):
                if not (sec["startPage"] <= p <= sec["endPage"]):
                    continue
                for para in matn_pages_by_vol[v][p]["paragraphs"]:
                    m = sub_heading_re.match(para.strip())
                    if m:
                        sh = re.split(r"\s+(?:قال ابن|قال البخاري|قال أحمد|ذكر البيهقي|روى )", m.group(0))[0].strip()
                        if 6 <= len(sh) <= 115:
                            sub_events.append({"page": p, "heading": sh})

            ev_obj = {
                "eventId": f"ev-{sec['id']}",
                "sectionId": sec["id"],
                "volume": v,
                "orderInVolume": sec["order"],
                "globalOrder": sec["globalOrder"],
                "title": sec["title"],
                "eraTag": sec["eraTag"],
                "startPage": sec["startPage"],
                "endPage": sec["endPage"],
                "pageCount": sec["pageCount"],
                "wordCount": sec["wordCount"],
                "characterIds": sec_chars,
                "sourceIds": sec_sources,
                "subEvents": sub_events[:20],
            }
            vol_events.append(ev_obj)
            all_events.append(ev_obj)

        (RESEARCH_DIR / "events" / f"vol_{v}_events.json").write_text(
            json.dumps({"volume": v, "eventCount": len(vol_events), "events": vol_events}, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )

    (RESEARCH_DIR / "events" / "all_events_index.json").write_text(
        json.dumps({"totalEvents": len(all_events), "events": all_events}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

